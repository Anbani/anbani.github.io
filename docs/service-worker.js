// Kill-switch service worker. next-pwa was removed from the build; this stub
// replaces the old workbox worker on returning visitors, clears its caches and
// unregisters itself so stale precached assets can't shadow the live site.
self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.map((key) => caches.delete(key)));
      await self.registration.unregister();
      const clients = await self.clients.matchAll({ type: 'window' });
      clients.forEach((client) => client.navigate(client.url));
    })()
  );
});
